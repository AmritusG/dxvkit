/*
 * Generates src/enc_tables.h: the single-colour BC1 endpoint tables and the nearest 5 / 6-bit
 * quantisation tables used by the encoder (src/enc_bc.c). Run: cc tools/gen_bc_tables.c && ./a.out
 * > src/enc_tables.h
 *
 * For each 8-bit target v: the endpoint pair (e0, e1) whose interpolated value, (2 e0 + e1) / 3
 * (four-colour) or (e0 + e1) / 2 (three-colour) with bit-replicated expansion and truncating division
 * (docs/spec/DXV_FORMAT.md 8.1), is closest to v; ties go to the closer pair.
 *
 * MIT License. Copyright (c) 2026 Amrit Rosell. See LICENSE.
 */
#include <stdio.h>
#include <stdlib.h>

static int expand(int v, int bits) { return bits == 5 ? (v << 3) | (v >> 2) : (v << 2) | (v >> 4); }

static void table(const char *name, int bits, int three)
{
    printf("static const solid_entry %s[256] = {\n", name);
    for (int v = 0; v < 256; v++) {
        int best = 1 << 30, e0 = 0, e1 = 0, err = 0;
        for (int a = 0; a < (1 << bits); a++)
            for (int b = 0; b < (1 << bits); b++) {
                int ea = expand(a, bits), eb = expand(b, bits);
                int val = three ? (ea + eb) / 2 : (2 * ea + eb) / 3;
                int score = abs(val - v) * 256 + abs(a - b);
                if (score < best)
                    best = score, e0 = a, e1 = b, err = abs(val - v);
            }
        printf("%s{%d, %d, %d},%s", v % 8 == 0 ? "    " : "", e0, e1, err, v % 8 == 7 ? "\n" : " ");
    }
    printf("};\n\n");
}

static void quant(const char *name, int bits)
{
    printf("static const uint8_t %s[256] = {\n", name);
    for (int v = 0; v < 256; v++) {
        int best = 0;
        for (int q = 1; q < (1 << bits); q++)
            if (abs(expand(q, bits) - v) < abs(expand(best, bits) - v))
                best = q;
        printf("%s%d,%s", v % 16 == 0 ? "    " : "", best, v % 16 == 15 ? "\n" : " ");
    }
    printf("};\n\n");
}

int main(void)
{
    printf("/* Generated by tools/gen_bc_tables.c. Do not edit. MIT License. Copyright (c) 2026 Amrit "
           "Rosell. */\n\n");
    table("solid_four5", 5, 0);
    table("solid_four6", 6, 0);
    table("solid_three5", 5, 1);
    table("solid_three6", 6, 1);
    quant("quant5", 5);
    quant("quant6", 6);
    return 0;
}
